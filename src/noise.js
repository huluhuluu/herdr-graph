"use strict";

// Noise filters shared by the adapters.
//
// The lists below are not guesses: they come from scanning every session file on
// this machine and tallying what non-human text leads a "user" message.
//
//   codex  (163 files): plain x1221, <environment_context> x112, <image> x13,
//                       <codex_internal_context> x8, <user_shell_command> x2
//   claude (37 files):  plain x598, "[Request interrupted by user]" x27,
//                       <local-command-caveat> x23, <command-name> x22,
//                       <local-command-stdout> x15, <task-notification> x5,
//                       <bash-input> x3, <bash-stdout> x3,
//                       "[Request interrupted by user for tool use]" x3,
//                       "[Image #1]" x1

const CODEX_WRAPPERS = [
  "environment_context",
  "codex_internal_context",
  "user_shell_command",
  "image",
];

// Injected context blocks that arrive as a plain "user" message but are not
// something the human typed. Measured on this machine:
//   "# AGENTS.md instructions" x90, "<environment_context>" x112
const CODEX_PREFIXES = [
  /^#\s*AGENTS\.md instructions/i,
  /^#\s*CLAUDE\.md instructions/i,
  /^#\s*Instructions\b/i,
  /^<user_instructions>/i,
  /^<turn_aborted>/i,
  /^<collaboration_mode>/i,
  /^<permissions instructions>/i,
  /^You are Codex,/i,
];

const CLAUDE_WRAPPERS = [
  "local-command-caveat",
  "local-command-stdout",
  "command-name",
  "command-message",
  "command-args",
  "task-notification",
  "bash-input",
  "bash-stdout",
  "bash-stderr",
];

// Claude injects these as "user" records. Measured on this machine:
//   "This session is being continued…" (also flagged isCompactSummary)
//   "<task-notification>" x5, "[Request interrupted by user]" x27
const CLAUDE_PREFIXES = [
  /^This session is being continued from a previous conversation/i,
  /^Caveat: The messages below were generated by the user while running local commands/i,
  /^<user_instructions>/i,
];

// Bracketed notices the CLI injects, not something the human typed.
const BRACKET_NOTICES = [
  /^\[Request interrupted by user[^\]]*\]$/i,
  /^\[Image #\d+\]$/i,
  /^\[Tool use rejected[^\]]*\]$/i,
  /^\[Request cancelled[^\]]*\]$/i,
];

function hasWrapper(text, tags) {
  const m = String(text).trimStart().match(/^<([a-zA-Z_][\w-]*)[\s>/]/);
  return !!m && tags.includes(m[1]);
}

function isBracketNotice(text) {
  const t = String(text).trim();
  return BRACKET_NOTICES.some(re => re.test(t));
}

// Decide whether a candidate user message is real human prose.
function isHumanText(text, kind) {
  const t = String(text ?? "").trim();
  if (!t) return false;
  if (isBracketNotice(t)) return false;
  if (kind === "codex") {
    if (CODEX_PREFIXES.some(re => re.test(t))) return false;
  } else {
    if (CLAUDE_PREFIXES.some(re => re.test(t))) return false;
  }
  const tags = kind === "claude" ? CLAUDE_WRAPPERS : CODEX_WRAPPERS;
  if (hasWrapper(t, tags)) {
    // A wrapper that also contains real prose is rare; treat it as noise so the
    // graph shows what the human actually asked.
    return false;
  }
  return true;
}

module.exports = { isBracketNotice, isHumanText };
